    private fun brand(name: String, evenOdd: Boolean, vararg layers: Layer): ImageVector {
        val builder = ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        )
        layers.forEach { layer ->
            builder.addPath(
                pathData = parse(layer.data),
                fill = SolidColor(Color.Black),
                fillAlpha = layer.alpha,
                pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
            )
        }
        return builder.build()
    }

